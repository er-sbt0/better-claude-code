#!/usr/bin/env bash
#
# Reproduces docs/verification/git-shadow-attribution.md.
#
# Proves that a run's worktree can be snapshotted into a private shadow history
# after every mutating tool call, that doing so never touches the user's HEAD,
# index or working tree, and that diff hunks can then be attributed back to the
# `seq` that produced them -- including mutations no tool call declared.
#
# Asserts rather than prints: exits non-zero on any regression, so it can be
# wired into CI when the git crate exists. Takes a few seconds.
#
#   bash docs/verification/shadow-attribution-spike.sh
#
set -euo pipefail

fail=0
ok()   { printf '  ok       %s\n' "$1"; }
bad()  { printf '  FAIL     %s\n' "$1"; fail=1; }
check(){ if [ "$2" = "$3" ]; then ok "$1"; else bad "$1 (want '$3', got '$2')"; fi; }

ROOT=$(mktemp -d); trap 'rm -rf "$ROOT"' EXIT
export GIT_CONFIG_GLOBAL=$ROOT/gitconfig GIT_CONFIG_SYSTEM=/dev/null
printf '[init]\n\tdefaultBranch = main\n[user]\n\tname = The User\n\temail = user@example.com\n' > "$GIT_CONFIG_GLOBAL"

echo "git $(git --version | awk '{print $3}')"

# ---------------------------------------------------------------- the primitive
# The only thing the process driver has to call. $1 = seq, $2 = tool,
# $3 = tool_use_id ("-" for the run-start root).
snapshot() {
  local seq=$1 tool=$2 tuid=$3 parent tree commit
  parent=$(git rev-parse --verify -q "$REF" || true)
  tree=$(GIT_INDEX_FILE=$SHADOW_INDEX sh -c 'git add -A && git write-tree')
  # An unchanged tree means the tool mutated nothing. No commit: a shadow
  # history with empty commits in it makes blame attribute to the wrong seq.
  if [ -n "$parent" ] && [ "$tree" = "$(git rev-parse "$parent^{tree}")" ]; then
    SNAP=""; return 0
  fi
  commit=$(GIT_AUTHOR_NAME=agent-workspace  GIT_AUTHOR_EMAIL=runtime@agent-workspace.local \
           GIT_COMMITTER_NAME=agent-workspace GIT_COMMITTER_EMAIL=runtime@agent-workspace.local \
           git commit-tree "$tree" ${parent:+-p "$parent"} \
             -m "seq $seq $tool" \
             -m "$(printf 'run: %s\nseq: %s\ntool: %s\ntool-use-id: %s' "$RUN" "$seq" "$tool" "$tuid")")
  git update-ref "$REF" "$commit"
  SNAP=$commit
}
seq_of() { git show -s --format='%(trailers:key=seq,valueonly,separator=)' "$1"; }
# seq that produced the first line of $2 containing the literal $1, or "" if gone.
seq_for_line() { awk -v pat="$1" -F'\t' 'index($2,pat){print $1; exit}' <<<"$2"; }
blame_seq() {  # $1 = file -> "seq<TAB>line" per line of the final version
  git blame --line-porcelain "$REF" -- "$1" \
    | awk '/^[0-9a-f]{40} /{c=substr($0,1,8)} /^\t/{printf "%s\t%s\n", c, substr($0,2)}' \
    | while IFS=$'\t' read -r c line; do printf '%s\t%s\n' "$(seq_of "$c")" "$line"; done
}

# ------------------------------------------------------------------ the fixture
REPO=$ROOT/my-app
git init -q "$REPO"; cd "$REPO"
mkdir -p src
cat > src/auth.ts <<'EOF'
export function refresh(token: string) {
  return fetch("/refresh", { method: "POST", body: token });
}

export function logout() {
  return fetch("/logout");
}
EOF
echo "node_modules/" > .gitignore
mkdir -p node_modules && echo junk > node_modules/x
git add -A && git commit -qm base

# The user has their own work in flight: one staged edit, one untracked file.
# Both must survive untouched. Note where they are: the MAIN checkout.
echo "// user's own scratch note" >> src/auth.ts
git add src/auth.ts
echo "untracked user file" > SCRATCH.md
BEFORE_HEAD=$(git rev-parse HEAD)
BEFORE_INDEX=$(git write-tree)
BEFORE_INDEX_MTIME=$(stat -c %Y .git/index)

# §13: a run gets its own worktree. That is where all of this happens.
RUN=run_1842
git worktree add -q "$ROOT/wt" -b "run/1842"
cd "$ROOT/wt"
# A fresh worktree is a clean checkout of the branch point, so the user's staged
# and untracked work is not here at all -- it cannot be swept into the run's
# history even in principle. What CAN mutate files before the first tool call is
# §13's post-create hook.
check "user's staged edit is absent from the run worktree" \
  "$(grep -c "scratch note" src/auth.ts || true)" "0"
check "user's untracked file is absent from the run worktree" \
  "$([ -e SCRATCH.md ] && echo present || echo absent)" "absent"
GITDIR=$(git rev-parse --git-dir)
REF=refs/agent-workspace/runs/$RUN
SHADOW_INDEX=$GITDIR/agent-workspace/$RUN.index
mkdir -p "$(dirname "$SHADOW_INDEX")"
# Seeding from the real index costs a file copy and saves re-hashing every file
# in the repo on the first snapshot (146ms -> 33ms on 10k files).
cp "$GITDIR/index" "$SHADOW_INDEX"

echo
echo "-- the run --"
# §13's post-create hook: dependency install, codegen. It runs before the agent
# does, and it writes files.
mkdir -p .cache && echo "generated by the post-create hook" > .cache/build-info
printf '\n// generated: do not edit\n' >> src/auth.ts
# seq 0: taken after the hook, before the first tool call, so hook output has
# somewhere to land other than the first Edit.
snapshot 0 - -
ROOT_SNAP=$SNAP

py() { python3 -c "$1"; }
py "p='src/auth.ts';s=open(p).read();open(p,'w').write(s.replace('  return fetch(\"/refresh\", { method: \"POST\", body: token });','  return retry(() => fetch(\"/refresh\", { method: \"POST\", body: token }), 3);'))"
snapshot 4 Edit toolu_01
cat > src/retry.ts <<'EOF'
export async function retry<T>(f: () => Promise<T>, n: number): Promise<T> {
  try { return await f(); } catch (e) { if (n <= 0) throw e; return retry(f, n - 1); }
}
EOF
snapshot 7 Write toolu_02
# The same file edited a second time -- the case that defeats matching hunks to
# Edit calls by comparing old_string/new_string.
py "p='src/auth.ts';s=open(p).read();open(p,'w').write(s.replace('  return fetch(\"/logout\");','  return retry(() => fetch(\"/logout\"), 2);'))"
snapshot 11 Edit toolu_03
# A Bash mutation. No tool record says which file or which lines.
printf '\nexport const VERSION = "1.0.0";\n' >> src/auth.ts
snapshot 14 Bash toolu_04
# A formatter, rewriting a file the model never named.
py "p='src/retry.ts';s=open(p).read();open(p,'w').write(s.replace('  try { return await f(); } catch (e) { if (n <= 0) throw e; return retry(f, n - 1); }','  try {\n    return await f();\n  } catch (e) {\n    if (n <= 0) throw e;\n    return retry(f, n - 1);\n  }'))"
snapshot 18 Bash toolu_05
# A tool call that mutates nothing (a Read, a failed Edit).
snapshot 19 Read toolu_07
NOOP_SNAP=$SNAP
# A deletion: logout() removed entirely.
py "p='src/auth.ts';s=open(p).read();i=s.index('export function logout()');j=s.index('}',s.index('retry(() => fetch(\"/logout\")'))+2;open(p,'w').write(s[:i]+s[j:])"
snapshot 21 Edit toolu_06

echo
echo "-- the user's own state is untouched --"
cd "$REPO"
check "HEAD unmoved"                  "$(git rev-parse HEAD)"   "$BEFORE_HEAD"
check "staged content byte-identical" "$(git write-tree)"       "$BEFORE_INDEX"
check ".git/index never written"      "$(stat -c %Y .git/index)" "$BEFORE_INDEX_MTIME"
check "ignored paths stay out"        "$(git ls-tree -r --name-only "$REF" | grep -c node_modules || true)" "0"
cd "$ROOT/wt"

echo
echo "-- shadow history --"
git log --format='     %h  seq=%(trailers:key=seq,valueonly,separator=) tool=%(trailers:key=tool,valueonly,separator=) id=%(trailers:key=tool-use-id,valueonly,separator=)' "$REF"
check "a tool that mutated nothing makes no commit" "${NOOP_SNAP:-none}" "none"
check "trailers are machine-readable" "$(seq_of "$REF")" "21"

echo
echo "-- attribution of the final diff --"
attr=$(blame_seq src/auth.ts)
retry_attr=$(blame_seq src/retry.ts)
check "Edit, first touch of the file"          "$(seq_for_line 'fetch("/refresh"' "$attr")"   "4"
check "Bash mutation with no tool record"      "$(seq_for_line 'VERSION = "1.0.0"' "$attr")"  "14"
check "formatter output in an undeclared file" "$(seq_for_line 'if (n <= 0)' "$retry_attr")"  "18"
check "post-create hook output is NOT a tool's" "$(seq_for_line 'generated: do not edit' "$attr")" "0"
check "hook-generated file is NOT a tool's"     "$(blame_seq .cache/build-info | cut -f1 | sed -n 1p)" "0"

# Blame only sees lines that survived. A deleted hunk is attributed by finding
# the newest shadow commit whose diff removed it.
# `-n 1` rather than `| head -1`: SIGPIPE under `set -o pipefail` fails the run.
deleter=$(git log --format='%H' -n 1 -S 'fetch("/logout")' "$REF" -- src/auth.ts)
check "deleted lines attribute to the deleting seq" "$(seq_of "$deleter")" "21"

echo
echo "-- Review's diff is fully covered by the shadow history --"
GIT_INDEX_FILE=$SHADOW_INDEX git add -A
check "worktree == shadow tip" \
  "$(GIT_INDEX_FILE=$SHADOW_INDEX git write-tree)" "$(git rev-parse "$REF^{tree}")"

echo
echo "-- the history outlives the worktree --"
cd "$REPO"
TIP=$(git rev-parse "$REF")
git worktree remove --force "$ROOT/wt"
git branch -qD run/1842
git reflog expire --expire=now --all
git gc --prune=now -q 2>/dev/null || true
check "survives worktree remove + branch delete + gc --prune=now" \
  "$(git rev-parse --verify -q "$TIP^{commit}" >/dev/null 2>&1 && echo yes || echo no)" "yes"
check "blame still answers afterwards" \
  "$(git blame --line-porcelain "$TIP" -- src/auth.ts >/dev/null 2>&1 && echo yes || echo no)" "yes"
echo "     object cost of the whole run: $(git count-objects -vH | awk '/size-pack/{print $2, $3}')"

echo
[ "$fail" = 0 ] && echo "all assertions passed" || { echo "FAILURES"; exit 1; }
